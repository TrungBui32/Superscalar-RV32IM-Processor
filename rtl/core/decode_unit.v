`timescale 1ns / 1ps


module decode_unit(
    input [31:0] Instruction,
    output reg illegal_instruction,
    input [6:0] Opcode ,
    input [2:0] Funct3 ,
    input [6:0] Funct7 ,
    input [4:0] Rs1,          // instruction[19:15]: register index or uimm
    output reg RegWrite,		// Asserted only by instructions which write to register file (load, auipc, lui, DPImm, DPReg);
    output MemRead,		// Asserted only by load (lw)
    output reg [2:0] MemWrite,		// Asserted only by store (sw)
    output MemtoReg,		// Asserted only by load (lw)
    output uses_rs1,
    output uses_rs2,
    output csr_rvalid,       // Valid CSR address access, including CSRRW rd=x0
    output csr_wvalid,       // Decoded write intent; qualify again at MEM
    output reg [4:0] LwSizeSel,        // 0001 for lb/lbu, 0011 for lh/lhu, 1111 for lw
    output reg [1:0] ALUSrcA, 	// Needed for lui, auipic. Refer to the microarchitecture for its use. Uncomment wire and port map in RV.v as well
    output reg [1:0] ALUSrcB,		// Asserted by all instructions which use an immediate (load, store, lui, auipc, DPImm). Needs to be expanded to a 2-bit signal to support link functionality for jal, jalr. Change wire width in RV.v as well
    output reg [2:0] ImmSrc, 	// 000 for U, 010 for UJ, 011 for I, 110 for S, 111 for SB.
    output reg [3:0] ALUControl,	// 0000 for add, 0001 for sub, 1110 for and, 1100 for or, 0010 for sll, 1010 for srl, 1011 for sra, 0001 for branch, 0000 for all others.
    					// Note that the most significant 3 bits are Funct3 for all DP instrns. LSB is the same as Funct[5] for DPReg type and DPImm_shifts. For other DPImms, Funct[5] is 0.
    					// It is the same as sub for branches, and add for all others not mentioned in the line above.
    output reg MCycle,		// Asserted by mul, mulh, mulhu, mulhsu, div, divu, rem, remu
    output wire atomic_valid,
    output reg [1:0] MCycleOp	// 00 for signed multiplication, 01 for unsigned multiplication, 10 for signed division, 11 for unsigned division. Generated by Control 
    );
// Change wire to reg if assigned inside a procedural (always) block. However, where it is easy enough, use assign instead of always.
// A 2-1 multiplexing can be done easily using an assign with a ternary operator
// For multiplexing with number of inputs > 2, a case construct within an always block is a natural fit. DO NOT to use nested ternary assignment operator as it hampers the readability of your code.
    localparam R_type_opcode = 7'b0110011;
    localparam I_type_opcode = 7'b0010011;
    localparam Load_opcode   = 7'b0000011;
    localparam Store_opcode  = 7'b0100011;
    localparam Branch_opcode = 7'b1100011;
    localparam JAL_opcode    = 7'b1101111;
    localparam JALR_opcode   = 7'b1100111;
    localparam LUI_opcode    = 7'b0110111;
    localparam AUIPC_opcode  = 7'b0010111;
    localparam CSR_opcode    = 7'b1110011;
    localparam A_opcode      = 7'b0101111;

    localparam Funct3_add_sub_reg   = 3'b000;
    localparam Funct3_add_imm   = 3'b000;
    localparam Funct3_and   = 3'b111;
    localparam Funct3_or    = 3'b110;
    localparam Funct3_sll   = 3'b001;
    localparam Funct3_slt   = 3'b010;
    localparam Funct3_sltu  = 3'b011;
    localparam Funct3_xor    = 3'b100;
    localparam Funct3_srl_sra   = 3'b101;
    localparam Funct3_mul = 3'b000; // for mul
    localparam Funct3_mulh = 3'b001; // for mulh
    localparam Funct3_mulu = 3'b011; // for mulhu
    localparam Funct3_mulsu = 3'b010; // for mulhsu
    localparam Funct3_div = 3'b100; // for div
    localparam Funct3_divu = 3'b101; // for divu
    localparam Funct3_rem = 3'b110; // for rem
    localparam Funct3_remu = 3'b111; // for div
    localparam Funct3_CSRRW = 3'b001;
    localparam Funct3_CSRRS = 3'b010;
    localparam Funct3_CSRRC = 3'b011;
    localparam Funct3_CSRRWI = 3'b101;
    localparam Funct3_CSRRSI = 3'b110;
    localparam Funct3_CSRRCI = 3'b111;
    localparam Funct3_A = 3'b010;

    localparam Funct7_add   = 7'b0000000;
    localparam Funct7_sub   = 7'b0100000;
    localparam Funct7_srl   = 7'b0000000;
    localparam Funct7_sra   = 7'b0100000;
    localparam Funct7_mul   = 7'b0000001; // for mul, mulh, mulhu, mulhsu
    localparam Funct7_div   = 7'b0000001; // for div, divu, rem, remu

    localparam Funct5_LRW = 5'b00010;
    localparam Funct5_SCW = 5'b00011;
    localparam Funct5_AMOSWAP = 5'b00001;
    localparam Funct5_AMOADD = 5'b00000;
    localparam Funct5_AMOAND = 5'b01100;
    localparam Funct5_AMOOR = 5'b01000;
    localparam Funct5_AMOXOR = 5'b00100;
    localparam Funct5_AMOMAX = 5'b10100;
    localparam Funct5_AMOMIN = 5'b10000;
    localparam Funct5_AMOMINU = 5'b11000;
    localparam Funct5_AMOMAXU = 5'b11100;

    wire [4:0] atomic_op = Instruction[31:27];
    wire atomic_lr = atomic_op == Funct5_LRW;
    wire atomic_encoding_valid = Funct3 == Funct3_A &&
        ((atomic_lr && Instruction[24:20] == 0) || atomic_op == Funct5_SCW ||
         atomic_op == Funct5_AMOSWAP || atomic_op == Funct5_AMOADD ||
         atomic_op == Funct5_AMOAND || atomic_op == Funct5_AMOOR ||
         atomic_op == Funct5_AMOXOR || atomic_op == Funct5_AMOMAX ||
         atomic_op == Funct5_AMOMIN || atomic_op == Funct5_AMOMINU ||
         atomic_op == Funct5_AMOMAXU);
    assign atomic_valid = Opcode == A_opcode && atomic_encoding_valid;


    always @(*) begin
        case(Opcode)
            R_type_opcode: RegWrite = 1'b1;
            I_type_opcode: RegWrite = 1'b1;
            Load_opcode:   RegWrite = 1'b1;
            LUI_opcode:    RegWrite = 1'b1;
            AUIPC_opcode:  RegWrite = 1'b1;
            JAL_opcode:    RegWrite = 1'b1;
            JALR_opcode:   RegWrite = 1'b1;
            CSR_opcode:    RegWrite = csr_rvalid;
            A_opcode:      RegWrite = atomic_valid;
            default:       RegWrite = 1'b0;
        endcase
    end


    always @(*) begin
        if(Opcode == Store_opcode) begin
            case(Funct3)
                3'b000: MemWrite = 3'b001; // sb
                3'b001: MemWrite = 3'b010; // sh
                3'b010: MemWrite = 3'b100; // sw
                default: MemWrite = 3'b000; // invalid
            endcase
        end
        else begin
            MemWrite = 3'b000; // no store, so no write enable for any byte
        end
    end

    assign MemRead = (Opcode == Load_opcode);
    // Atomic results use the registered memory-result writeback path.
    assign MemtoReg = (Opcode == Load_opcode) || atomic_valid;

    always @(*) begin
        if(Opcode == Load_opcode) begin
            case(Funct3)
                3'b000: LwSizeSel = 5'b00001; // lb
                3'b001: LwSizeSel = 5'b00010; // lh
                3'b010: LwSizeSel = 5'b00100; // lw
                3'b100: LwSizeSel = 5'b01000; // lbu
                3'b101: LwSizeSel = 5'b10000; // lhu
                default: LwSizeSel = 5'b00000; // invalid
            endcase
        end
        else begin
            LwSizeSel = 5'b00000;
        end
    end


    always @(*) begin
        case(Opcode)
            LUI_opcode:   ALUSrcA = 2'b01; // U-type
            AUIPC_opcode: ALUSrcA = 2'b10; // AUIPC
            CSR_opcode: ALUSrcA = (csr_rvalid && Funct3[2]) ? 2'b11 : 2'b00;
            default:      ALUSrcA = 2'b00; // Other types
        endcase
    end


    always @(*) begin
        case(Opcode)
            R_type_opcode: ALUSrcB = 2'b00; // reg
            I_type_opcode: ALUSrcB = 2'b01; // imm
            Load_opcode:  ALUSrcB = 2'b01; // imm
            Store_opcode: ALUSrcB = 2'b01; // imm
            LUI_opcode:   ALUSrcB = 2'b01; // imm
            AUIPC_opcode: ALUSrcB = 2'b01; // imm
            Branch_opcode: ALUSrcB = 2'b00; // reg
            CSR_opcode: ALUSrcB = 2'b10; // old CSR value
            default:      ALUSrcB = 2'b00; // reg
        endcase
    end

    always @(*) begin
        case(Opcode)
            LUI_opcode:   ImmSrc = 3'b000; // U-type
            AUIPC_opcode: ImmSrc = 3'b000; // U-type
            JAL_opcode:   ImmSrc = 3'b010; // UJ-type
            JALR_opcode:  ImmSrc = 3'b011; // I-type
            I_type_opcode:ImmSrc = 3'b011; // I-type
            Load_opcode:  ImmSrc = 3'b011; // I-type
            Store_opcode: ImmSrc = 3'b110; // S-type
            Branch_opcode:ImmSrc = 3'b111; // SB-type
            default:      ImmSrc = 3'bxxx; // Don't care
        endcase
    end

    always @(*) begin
        case(Opcode)
            R_type_opcode: begin
                case(Funct3)
                    Funct3_add_sub_reg: begin
                        if (Funct7 == Funct7_sub)
                            ALUControl = 4'b0001; // sub
                        else
                            ALUControl = 4'b0000; // add
                    end
                    Funct3_and: ALUControl = 4'b1110; // and
                    Funct3_or:  ALUControl = 4'b1100; // or
                    Funct3_sll: ALUControl = 4'b0010; // sll
                    Funct3_slt: ALUControl = 4'b1000; // slt
                    Funct3_sltu:ALUControl = 4'b1001; // sltu
                    Funct3_xor: ALUControl = 4'b1101; // xor
                    Funct3_srl_sra: begin
                        if (Funct7 == Funct7_sra)
                            ALUControl = 4'b1011; // sra
                        else
                            ALUControl = 4'b1010; // srl
                    end
                    default: ALUControl = 4'bxxxx; // Don't care
                endcase
            end
            I_type_opcode: begin
                case(Funct3)
                    Funct3_add_imm: ALUControl = 4'b0000; // addi
                    Funct3_and:     ALUControl = 4'b1110; // andi
                    Funct3_or:      ALUControl = 4'b1100; // ori
                    Funct3_sll:     ALUControl = 4'b0010; // slli
                    Funct3_slt:     ALUControl = 4'b1000; // slti
                    Funct3_sltu:    ALUControl = 4'b1001; // sltiu
                    Funct3_xor:     ALUControl = 4'b1101; // xori
                    Funct3_srl_sra: begin
                        if (Funct7 == Funct7_sra)
                            ALUControl = 4'b1011; // srai
                        else
                            ALUControl = 4'b1010; // srli
                    end
                    default: ALUControl = 4'bxxxx; // Don't care
                endcase
            end
            A_opcode: ALUControl = 4'b0000; // Core bypasses address directly from rs1.
            Load_opcode: ALUControl = 4'b0000; // add (for address calculation)
            Store_opcode: ALUControl = 4'b0000; // add (for address calculation)
            Branch_opcode: ALUControl = 4'b0001; // sub (for comparison)
            JAL_opcode: ALUControl = 4'b0000; // add (for address calculation)
            LUI_opcode: ALUControl = 4'b0000; // add (for loading immediate)
            CSR_opcode: begin
                case (Funct3)
                    Funct3_CSRRS, Funct3_CSRRSI: ALUControl = 4'b1100;
                    Funct3_CSRRC, Funct3_CSRRCI: ALUControl = 4'b1111; // B & ~A
                    default: ALUControl = 4'b0000; // CSRRW[I] uses operand bypass
                endcase
            end
            AUIPC_opcode: ALUControl = 4'b0000; //
            default: ALUControl = 4'bxxxx;
    endcase
    end

    always @(*) begin
        if(Opcode == R_type_opcode && Funct7 == Funct7_mul)
            MCycle = 1'b1;
        else
            MCycle = 1'b0;
    end

    always @(*) begin
        if(Opcode == R_type_opcode && Funct7 == Funct7_mul) begin
            case(Funct3)
                Funct3_mul: MCycleOp = 2'b00; // signed multiplication
                Funct3_mulh: MCycleOp = 2'b00; // signed multiplication
                Funct3_mulu: MCycleOp = 2'b01; // unsigned multiplication
                Funct3_mulsu: MCycleOp = 2'b01; // unsigned multiplication
                Funct3_div: MCycleOp = 2'b10; // signed division
                Funct3_divu: MCycleOp = 2'b11; // unsigned division
                Funct3_rem: MCycleOp = 2'b10; // signed division
                Funct3_remu: MCycleOp = 2'b11; // unsigned division
                default: MCycleOp = 2'bxx; // Don't care
            endcase
        end
        else
            MCycleOp = 2'bxx; // Don't care
    end

    assign csr_rvalid = (Opcode == CSR_opcode) &&
                  ((Funct3 == Funct3_CSRRW)  ||
                   (Funct3 == Funct3_CSRRS)  ||
                   (Funct3 == Funct3_CSRRC)  ||
                   (Funct3 == Funct3_CSRRWI) ||
                   (Funct3 == Funct3_CSRRSI) ||
                   (Funct3 == Funct3_CSRRCI));
    // Real GPR sources only: CSR immediates are not register operands.
    assign uses_rs1 = (Opcode == R_type_opcode) || (Opcode == I_type_opcode) ||
                      (Opcode == Load_opcode) || (Opcode == Store_opcode) ||
                      (Opcode == Branch_opcode) || (Opcode == JALR_opcode) ||
                      (csr_rvalid && !Funct3[2]) || atomic_valid;
    assign uses_rs2 = (Opcode == R_type_opcode) || (Opcode == Store_opcode) ||
                      (Opcode == Branch_opcode) || (atomic_valid && !atomic_lr);

    // Encoding legality; privilege/CSR existence is checked by the CSR bank.
    always @(*) begin
        illegal_instruction = 1'b0;
        case (Opcode)
            R_type_opcode: illegal_instruction = !((Funct7 == 0) || (Funct7 == 1) ||
                (Funct7 == 7'h20 && (Funct3 == 0 || Funct3 == 5)));
            I_type_opcode: begin
                if (Funct3 == 1) illegal_instruction = (Funct7 != 0);
                else if (Funct3 == 5) illegal_instruction = !(Funct7 == 0 || Funct7 == 7'h20);
            end
            Load_opcode: illegal_instruction = !(Funct3 == 0 || Funct3 == 1 || Funct3 == 2 || Funct3 == 4 || Funct3 == 5);
            Store_opcode: illegal_instruction = !(Funct3 == 0 || Funct3 == 1 || Funct3 == 2);
            Branch_opcode: illegal_instruction = (Funct3 == 2 || Funct3 == 3);
            JALR_opcode: illegal_instruction = (Funct3 != 0);
            LUI_opcode, AUIPC_opcode, JAL_opcode: begin end
            7'h0f: illegal_instruction = !(Funct3 == 0 || Funct3 == 1);
            CSR_opcode: illegal_instruction = !csr_rvalid &&
                !(Instruction == 32'h00000073 || Instruction == 32'h00100073 ||
                  Instruction == 32'h30200073 || Instruction == 32'h10200073 ||
                  Instruction == 32'h10500073);
            A_opcode: illegal_instruction = !atomic_encoding_valid;
            default: illegal_instruction = 1'b1;
        endcase
    end

    // Register forms test the register INDEX, not its runtime value.
    // Immediate forms use the same instruction field as a five-bit uimm.
    assign csr_wvalid = csr_rvalid &&
                        ((Funct3[1:0] == 2'b01) || (Rs1 != 5'd0));
  
endmodule



