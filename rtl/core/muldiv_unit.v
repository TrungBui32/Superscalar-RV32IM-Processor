`timescale 1ns / 1ps


module muldiv_unit

    #(parameter width = 4) // Keep this at 4 to verify your algorithms with 4 bit numbers (easier). When using MCycle as a component in ARM, generic map it to 32.
    (
        input CLK,
        input RESET, // Connect this to the reset of the ARM processor.
        input Start, // Multi-cycle Enable. The control unit should assert this when an instruction with a multi-cycle operation is detected.
        input [1:0] MCycleOp, // Multi-cycle Operation. "00" for signed multiplication, "01" for unsigned multiplication, "10" for signed division, "11" for unsigned division. Generated by Control unit
        input is_mulsu, // high if the operation is mulhsu
        input [width-1:0] Operand1, // Multiplicand / Dividend
        input [width-1:0] Operand2, // Multiplier / Divisor
        output reg [width-1:0] Result1, // LSW of Product / Quotient
        output reg [width-1:0] Result2, // MSW of Product / Remainder
        output reg Busy // Set immediately when Start is set. Cleared when the Results become ready. This bit can be used to stall the processor while multi-cycle operations are on.
    );
    
// use the Busy signal to reset WE_PC to 0 in ARM.v (aka "freeze" PC). The two signals are complements of each other
// since the IDLE_PROCESS is combinational, instantaneously asserts Busy once Start is asserted
  
    parameter IDLE = 1'b0;  // will cause a warning which is ok to ignore - [Synth 8-2507] parameter declaration becomes local in MCycle with formal parameter declaration list...

    parameter COMPUTING = 1'b1; // this line will also cause the above warning
    reg state = IDLE;
    reg n_state = IDLE;
   
    reg done;
    reg [7:0] count = 0; // assuming no computation takes more than 256 cycles.
    reg [2*width+4:0] shifted_op_reg;
    reg [width:0] op2_reg;
    reg [2*width+4:0] shifted_op_comb;
    reg [width+3:0] temp_sum;
    reg quotient_sign, remainder_sign; // to store the sign of quotient and remainder in division

    reg[width+3:0] op1_8M_pos; // 8 tuple multiplicand for Booth's algorithm
    reg[width+3:0] op1_8M_neg; // negated 8 tuple multiplicand for Booth's algorithm
    reg[width+3:0] op1_7M_pos; // 7 tuple multiplicand for Booth's algorithm
    reg[width+3:0] op1_7M_neg; // negated 7 tuple multiplicand for Booth's algorithm
    reg[width+3:0] op1_6M_pos; // 6 tuple multiplicand for Booth's algorithm
    reg[width+3:0] op1_6M_neg; // negated 6 tuple multiplicand for Booth's algorithm
    reg[width+3:0] op1_5M_pos; // 5 tuple multiplicand for Booth's algorithm
    reg[width+3:0] op1_5M_neg; // negated 5 tuple multiplicand for Booth's algorithm
    reg[width+3:0] op1_4M_pos; // quadruple multiplicand for Booth's algorithm
    reg[width+3:0] op1_4M_neg; // negated quadruple multiplicand for Booth's algorithm
    reg[width+3:0] op1_3M_pos; // triple multiplicand for Booth's algorithm
    reg[width+3:0] op1_3M_neg; // negated triple multiplicand for Booth's algorithm
    reg[width+3:0] op1_2M_pos; // double multiplicand for Booth's algorithm
    reg[width+3:0] op1_2M_neg; // double multiplier for Booth's algorithm
    reg[width+3:0] op1_M_pos; // negated multiplicand for Booth's algorithm
    reg[width+3:0] op1_M_neg; // negated multiplicand for Booth's algorithm

    always@(*) begin : IDLE_PROCESS
		// Note : This block uses non-blocking assignments to get around an unpredictable Verilog simulation behaviour.
        // default outputs
        n_state = IDLE;
        Busy = 1'b0;
        // reset
        if(~RESET)
            case(state)
                IDLE: begin
                    if(Start) begin // note: a mealy machine, since output depends on current state (IDLE) & input (Start)
                        n_state = COMPUTING;
                        Busy = 1'b1;
                    end
                end
                COMPUTING: begin
                    if(~done) begin
                        n_state = COMPUTING;
                        Busy = 1'b1;
                    end                  
                end        
            endcase    
    end


    always@( posedge CLK ) begin : STATE_UPDATE_PROCESS // state updating
        state <= n_state;    
    end



    integer i;
    always @(*) begin
        if(RESET)
            shifted_op_comb = 0;
        else begin
            shifted_op_comb = shifted_op_reg;
            if(MCycleOp[1:0] == 2'b01) begin // unsigned multiplication
                for(i = 0; i < 4; i = i + 1) begin
                    if(shifted_op_comb[0]) begin// add only if b0 = 1
                        temp_sum[width:0] = shifted_op_comb[2*width-1:width] + op2_reg[width:0];
                    end
                    else begin
                        temp_sum[width:0] = shifted_op_comb[2*width-1:width];
                    end
                    shifted_op_comb [2*width-1:width] = temp_sum[width-1:0];
                    shifted_op_comb = {temp_sum[width], shifted_op_comb[2*width-1:1]};
                end
            end
            else 
            if(MCycleOp[1:0] == 2'b00) begin
                case(shifted_op_comb[4:0]) // Booth's algorithm
                    5'b00000, 5'b11111: begin // do nothing
                        temp_sum[width+3:0] = shifted_op_comb[2*width+4:width+1];
                        shifted_op_comb[2*width+4:width+1] = temp_sum[width+3:0];
                    end
                    5'b00001, 5'b00010: begin // add M
                        temp_sum[width+3:0] = shifted_op_comb[2*width+4:width+1] + op1_M_pos[width+3:0];
                        shifted_op_comb[2*width+4:width+1] = temp_sum[width+3:0];
                    end
                    5'b00011, 5'b00100: begin // add 2M
                        temp_sum[width+3:0] = shifted_op_comb[2*width+4:width+1] + op1_2M_pos[width+3:0];
                        shifted_op_comb[2*width+4:width+1] = temp_sum[width+3:0];
                    end
                    5'b00101, 5'b00110: begin // add 3M
                        temp_sum[width+3:0] = shifted_op_comb[2*width+4:width+1] + op1_3M_pos[width+3:0];
                        shifted_op_comb[2*width+4:width+1] = temp_sum[width+3:0];
                    end
                    5'b00111, 5'b01000: begin // add 4M
                        temp_sum[width+3:0] = shifted_op_comb[2*width+4:width+1] + op1_4M_pos[width+3:0];
                        shifted_op_comb[2*width+4:width+1] = temp_sum[width+3:0];
                    end
                    5'b01001, 5'b01010: begin // add 5M
                        temp_sum[width+3:0] = shifted_op_comb[2*width+4:width+1] + op1_5M_pos[width+3:0];
                        shifted_op_comb[2*width+4:width+1] = temp_sum[width+3:0];
                    end
                    5'b01011, 5'b01100: begin // add 6M
                        temp_sum[width+3:0] = shifted_op_comb[2*width+4:width+1] + op1_6M_pos[width+3:0];
                        shifted_op_comb[2*width+4:width+1] = temp_sum[width+3:0];
                    end
                    5'b01101, 5'b01110: begin // add 7M
                        temp_sum[width+3:0] = shifted_op_comb[2*width+4:width+1] + op1_7M_pos[width+3:0];
                        shifted_op_comb[2*width+4:width+1] = temp_sum[width+3:0];
                    end
                    5'b01111: begin // add 8M
                        temp_sum[width+3:0] = shifted_op_comb[2*width+4:width+1] + op1_8M_pos[width+3:0];
                        shifted_op_comb[2*width+4:width+1] = temp_sum[width+3:0];
                    end
                    5'b10000: begin // sub 8M
                        temp_sum[width+3:0] = shifted_op_comb[2*width+4:width+1] + op1_8M_neg[width+3:0];
                        shifted_op_comb[2*width+4:width+1] = temp_sum[width+3:0];
                    end
                    5'b10001, 5'b10010: begin // sub 7M
                        temp_sum[width+3:0] = shifted_op_comb[2*width+4:width+1] + op1_7M_neg[width+3:0];
                        shifted_op_comb[2*width+4:width+1] = temp_sum[width+3:0];
                    end
                    5'b10011, 5'b10100: begin // sub 6M
                        temp_sum[width+3:0] = shifted_op_comb[2*width+4:width+1] + op1_6M_neg[width+3:0];
                        shifted_op_comb[2*width+4:width+1] = temp_sum[width+3:0];
                    end
                    5'b10101, 5'b10110: begin // sub 5M
                        temp_sum[width+3:0] = shifted_op_comb[2*width+4:width+1] + op1_5M_neg[width+3:0];
                        shifted_op_comb[2*width+4:width+1] = temp_sum[width+3:0];
                    end
                    5'b10111, 5'b11000: begin // sub 4M
                        temp_sum[width+3:0] = shifted_op_comb[2*width+4:width+1] + op1_4M_neg[width+3:0];
                        shifted_op_comb[2*width+4:width+1] = temp_sum[width+3:0];
                    end
                    5'b11001, 5'b11010: begin // sub 3M
                        temp_sum[width+3:0] = shifted_op_comb[2*width+4:width+1] + op1_3M_neg[width+3:0];
                        shifted_op_comb[2*width+4:width+1] = temp_sum[width+3:0];
                    end
                    5'b11011, 5'b11100: begin // sub 2M
                        temp_sum[width+3:0] = shifted_op_comb[2*width+4:width+1] + op1_2M_neg[width+3:0];
                        shifted_op_comb[2*width+4:width+1] = temp_sum[width+3:0];
                    end
                    5'b11101, 5'b11110: begin // sub M
                        temp_sum[width+3:0] = shifted_op_comb[2*width+4:width+1] + op1_M_neg[width+3:0];
                        shifted_op_comb[2*width+4:width+1] = temp_sum[width+3:0];
                    end
                endcase
                shifted_op_comb[2*width+4:0] = {{4{shifted_op_comb[2*width+4]}}, shifted_op_comb[2*width+4:4]};
            end
            else begin
                for(i = 0; i < 4; i = i + 1) begin
                    if(shifted_op_comb[2*width]) begin
                        shifted_op_comb[2*width:0] = {shifted_op_comb[2*width-1:0], 1'b0};
                        temp_sum[width:0] = shifted_op_comb[2*width:width] + op2_reg[width:0]; // add back divisor
                        shifted_op_comb[2*width:width] = temp_sum[width:0];
                    end
                    else begin
                        shifted_op_comb[2*width:0] = {shifted_op_comb[2*width-1:0], 1'b0};
                        temp_sum[width:0] = shifted_op_comb[2*width:width] + {~op2_reg[width:0] + 1'b1}; // subtract divisor
                        shifted_op_comb[2*width:width] = temp_sum[width:0];
                    end
                    if(shifted_op_comb[2*width] == 1)
                        shifted_op_comb[0] = 1'b0; // quotient bit = 0
                    else
                        shifted_op_comb[0] = 1'b1; // quotient bit = 1
                end
            end
        end
    end

    always @(*) begin
        if(RESET) begin
            op1_M_pos = 0;
        end
        else if(state == IDLE & n_state == COMPUTING & MCycleOp[1:0] == 2'b00) begin // signed multiplication
            op1_M_pos[width+3:0] = {{4{Operand1[width-1]}},Operand1};
        end
        else begin
            op1_M_pos = op1_M_pos;
        end
    end

    always @(*) begin
        if(RESET) begin
            op1_M_neg = 0;
        end
        else if(state == IDLE & n_state == COMPUTING & MCycleOp[1:0] == 2'b00) begin // signed multiplication
            op1_M_neg[width+3:0] = ~op1_M_pos[width+3:0] + 1'b1;
        end
        else begin
            op1_M_neg = op1_M_neg;
        end
    end

    always @(*) begin
        if(RESET) begin
            op1_2M_pos = 0;
        end
        else if(state == IDLE & n_state == COMPUTING & MCycleOp[1:0] == 2'b00) begin // signed multiplication
            op1_2M_pos[width+3:0] = {{3{Operand1[width-1]}}, Operand1, 1'b0};
        end
        else begin
            op1_2M_pos = op1_2M_pos;
        end
    end
    
    always @(*) begin
        if(RESET) begin
            op1_2M_neg = 0;
        end
        else if(state == IDLE & n_state == COMPUTING & MCycleOp[1:0] == 2'b00) begin // signed multiplication
            op1_2M_neg[width+3:0] = {~op1_2M_pos[width+3:0] + 1'b1};
        end
        else begin
            op1_2M_neg = op1_2M_neg;
        end
    end

    always @(*) begin
        if(RESET) begin
            op1_3M_pos = 0;
        end
        else if(state == IDLE & n_state == COMPUTING & MCycleOp[1:0] == 2'b00) begin // signed multiplication
            op1_3M_pos[width+3:0] = op1_2M_pos + op1_M_pos;
        end
        else begin
            op1_3M_pos = op1_3M_pos;
        end
    end

    always @(*) begin
        if(RESET) begin
            op1_3M_neg = 0;
        end
        else if(state == IDLE & n_state == COMPUTING & MCycleOp[1:0] == 2'b00) begin // signed multiplication
            op1_3M_neg[width+3:0] = op1_2M_neg + op1_M_neg;
        end
        else begin
            op1_3M_neg = op1_3M_neg;
        end
    end

    always @(*) begin
        if(RESET) begin
            op1_4M_pos = 0;
        end
        else if(state == IDLE & n_state == COMPUTING & MCycleOp[1:0] == 2'b00) begin // signed multiplication
            op1_4M_pos[width+3:0] = {{2{Operand1[width-1]}}, Operand1, 2'b00};
        end
        else begin
            op1_4M_pos = op1_4M_pos;
        end
    end

    always @(*) begin
        if(RESET) begin
            op1_4M_neg = 0;
        end
        else if(state == IDLE & n_state == COMPUTING & MCycleOp[1:0] == 2'b00) begin // signed multiplication
            op1_4M_neg[width+3:0] = {~op1_4M_pos[width+3:0] + 1'b1};
        end
        else begin
            op1_4M_neg = op1_4M_neg;
        end
    end

    always @(*) begin
        if(RESET) begin
            op1_5M_pos = 0;
        end
        else if(state == IDLE & n_state == COMPUTING & MCycleOp[1:0] == 2'b00) begin // signed multiplication
            op1_5M_pos[width+3:0] = op1_4M_pos + op1_M_pos;
        end
        else begin
            op1_5M_pos = op1_5M_pos;
        end
    end

    always @(*) begin
        if(RESET) begin
            op1_5M_neg = 0;
        end
        else if(state == IDLE & n_state == COMPUTING & MCycleOp[1:0] == 2'b00) begin // signed multiplication
            op1_5M_neg[width+3:0] = op1_4M_neg + op1_M_neg;
        end
        else begin
            op1_5M_neg = op1_5M_neg;
        end
    end

    always @(*) begin
        if(RESET) begin
            op1_6M_pos = 0;
        end
        else if(state == IDLE & n_state == COMPUTING & MCycleOp[1:0] == 2'b00) begin // signed multiplication
            op1_6M_pos[width+3:0] = op1_4M_pos + op1_2M_pos;
        end
        else begin
            op1_6M_pos = op1_6M_pos;
        end
    end

    always @(*) begin
        if(RESET) begin
            op1_6M_neg = 0;
        end
        else if(state == IDLE & n_state == COMPUTING & MCycleOp[1:0] == 2'b00) begin // signed multiplication
            op1_6M_neg[width+3:0] = op1_4M_neg + op1_2M_neg;
        end
        else begin
            op1_6M_neg = op1_6M_neg;
        end
    end

    always @(*) begin
        if(RESET) begin
            op1_7M_pos = 0;
        end
        else if(state == IDLE & n_state == COMPUTING & MCycleOp[1:0] == 2'b00) begin // signed multiplication
            op1_7M_pos[width+3:0] = op1_6M_pos + op1_M_pos;
        end
        else begin
            op1_7M_pos = op1_7M_pos;
        end
    end

    always @(*) begin
        if(RESET) begin
            op1_7M_neg = 0;
        end
        else if(state == IDLE & n_state == COMPUTING & MCycleOp[1:0] == 2'b00) begin // signed multiplication
            op1_7M_neg[width+3:0] = op1_8M_neg + op1_M_pos;
        end
        else begin
            op1_7M_neg = op1_7M_neg;
        end
    end

    always @(*) begin
        if(RESET) begin
            op1_8M_pos = 0;
        end
        else if(state == IDLE & n_state == COMPUTING & MCycleOp[1:0] == 2'b00) begin // signed multiplication
            op1_8M_pos[width+3:0] = {{{Operand1[width-1]}},Operand1, 3'b000};
        end
        else begin
            op1_8M_pos = op1_8M_pos;
        end
    end

    always @(*) begin
        if(RESET) begin
            op1_8M_neg = 0;
        end
        else if(state == IDLE & n_state == COMPUTING & MCycleOp[1:0] == 2'b00) begin // signed multiplication
            op1_8M_neg[width+3:0] = ~op1_8M_pos[width+3:0] + 1'b1;
        end
        else begin
            op1_8M_neg = op1_8M_neg;
        end
    end



    always @(posedge CLK) begin : SHIFTED_OP_REG_PROCESS
        if(RESET || n_state == IDLE) begin
            shifted_op_reg <= 0;
            op2_reg <= 0;
            count <= 0;
            temp_sum <= 0;
            quotient_sign <= 0;
            remainder_sign <= 0;
        end
        else if(n_state == COMPUTING & state == IDLE) begin // we are just transitioning into COMPUTING
            count <= 0;
            temp_sum <= 0;
            if(MCycleOp[1:0] == 2'b10) begin //signed division
                quotient_sign <= Operand1[width-1] ^ Operand2[width-1]; // sign of quotient
                remainder_sign <= Operand1[width-1]; // sign of remainder same as dividend
                shifted_op_reg[width-1:0] <= (Operand1[width-1] ? (~Operand1 + 1'b1) : Operand1); // make operands positive if they are negative
                shifted_op_reg[2*width-1:width] <= {width{1'b0}}; // upper half of dividend is 0
                op2_reg[width-1:0] <= (Operand2[width-1] ? (~Operand2 + 1'b1) : Operand2);
                op2_reg[width] <= 1'b0;
            end
            else
            if(MCycleOp[1:0] == 2'b00) begin // signed multiplication
                shifted_op_reg[2*width+4:width+1] <= {width+3{1'b0}}; // upper half of product is 0
                shifted_op_reg[width:1] <= Operand2[width-1:0];
                shifted_op_reg[0] <= 1'b0; // extra bit for Booth's algorithm
                quotient_sign <= 0;
                remainder_sign <= 0;
            end
            else begin // unsigned multiplication or unsigned division
                if(is_mulsu && Operand1[width-1] == 1'b1) begin
                    shifted_op_reg[width-1:0] <= ~Operand1[width-1:0] + 1'b1; // make operand negative
                end
                else
                    shifted_op_reg[width-1:0] <= Operand1[width-1:0]; 
                shifted_op_reg[2*width-1:width] <= {width{1'b0}}; // upper half of product is 0
                op2_reg[width:0] <= Operand2[width-1:0];
                quotient_sign <= 1'b0; // not used in multiplication & unsigned division
                remainder_sign <= 1'b0; // not used in multiplication & unsigned division
            end
        end
        else if(n_state == COMPUTING & state == COMPUTING) begin
            shifted_op_reg <= shifted_op_comb;
            op2_reg <= op2_reg;
            count <= count + 4;
        end
    end


    always @(posedge CLK) begin
        if(count == width) begin
            if(~MCycleOp[1]) begin // multiplication
                if(MCycleOp[0] == 1'b0) begin// signed multiplication
                    Result1 <= shifted_op_reg[width:1]; //corrected to ignore the extra bit for Booth's algorithm
                    Result2 <= shifted_op_reg[2*width:width+1]; //corrected to ignore the extra bit for Booth's algorithm
                end
                else begin // unsigned multiplication
                    if(is_mulsu && Operand1[width-1] == 1'b1) begin // mulhsu
                        {Result2, Result1} <= ~shifted_op_reg[2*width-1:0] + 1; // negate the result
                    end
                    else 
                        {Result2, Result1} <= shifted_op_reg[2*width-1:0];
                end
            end
            else begin // division
                // DIV/DIVU by zero return all ones, independent of dividend sign.
                if(op2_reg == 0)
                    Result1 <= {width{1'b1}};
                else if(quotient_sign)
                    Result1 <= ~shifted_op_reg[width-1:0] + 1; // make quotient negative if needed
                else
                    Result1 <= shifted_op_reg[width-1:0];

                if(shifted_op_reg[2*width]) begin
                    if(remainder_sign)
                        Result2 <= ~(shifted_op_reg[2*width-1:width] + op2_reg[width-1:0] ) + 1 ; // if remainder is negative, add back divisor to make it positive, then make it negative again
                    else
                        Result2 <= shifted_op_reg[2*width-1:width] + op2_reg[width-1:0] ;
                end
                else begin
                    if(remainder_sign)
                        Result2 <= ~shifted_op_reg[2*width-1:width] + 1 ; // if remainder is positive, do nothing. If remainder is negative, make it negative again (since we added back the divisor to make it positive)
                    else
                        Result2 <= shifted_op_reg[2*width-1:width] ;
                end
            end
            done <= 1'b1;
        end
        else
            done <= 1'b0;
    end

endmodule
